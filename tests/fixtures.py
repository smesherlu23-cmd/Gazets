"""Образец выпуска для тестов.

В самой программе демонстрационного содержимого нет: пользователь начинает с
чистого листа. Но проверять вёрстку, вместимость и экспорт нужно на настоящем
материале, поэтому «Вечерний вестник» из дизайн-пакета живёт здесь.
"""

from __future__ import annotations

from pechatnya.models import Article, Brand, ImageRef, Issue, Project, Publication
from pechatnya.presets import make_module, new_project

SAMPLE_BODY = """Ночью, около половины первого, в третьем пролёте Нижнего дока обрушилась часть кровли. Сторож услышал треск и успел вывести двоих грузчиков прежде, чем балка легла на настил. По словам портового мастера, кровлю держали на честном слове ещё с прошлой зимы: смету на починку отклонили дважды.

## У ВОРОТ С УТРА

Собралась артель — люди требовали объяснений и платы за простой. Управа выставила двух постовых, но до сору дело не дошло. К полудню движение через третий пролёт закрыли на трое суток, грузы направили на Верхнюю пристань, где и без того тесно.

Смотритель складов отстранён до окончания дознания. В конторе нам сказали, что бумаги по прошлогодней смете «находятся в работе» и будут предъявлены дознавателю в понедельник.

## ЧТО ГОВОРЯТ АРТЕЛЬНЫЕ

Платить за простой некому, а зима близко. Трое из шестерых работали без записи в книге, и на них конторские бумаги вовсе не заведены.

Старший артели Кузьма Долев показал нам тетрадь, где отмечены выходы за апрель и май. По его счёту, конторе следует уплатить сорок два рубля с полтиной — за дни, когда люди являлись к воротам и работы им не давали.

## КАК БУДЕТ ИДТИ ГРУЗ

Верхняя пристань примет на себя весь мелкий каботаж, крупные суда будут разгружаться на рейде с барж. По оценке мастера, это удлинит оборот на полдня.

Редакция будет следить за делом и печатать ответы конторы без сокращений."""


def sample_publication() -> Publication:
    brand = Brand(
        name_latin="Harbour Gazette",
        name_cyrillic="ВЕСТНИК",
        superline_enabled=True,
        superline="ВЕЧЕРНИЙ",
        motto="Выходит ежедневно, кроме воскресных дней и табельных праздников",
        rubricator=["ХРОНИКА ПРОИСШЕСТВИЙ", "ГОРОДСКАЯ ЖИЗНЬ", "ПОРТ И ТОРГ", "ОБЪЯВЛЕНИЯ"],
    )
    return Publication(
        name="Вечерний вестник",
        brand=brand,
        masthead_left="ПОДПИСКА НА МЕСЯЦ|1 р. 20 к.|с доставкой на дом",
        masthead_right="ОБЪЯВЛЕНИЯ|8 к. за строку|позади текста — дешевле",
        year_line="Год издания шестой",
        city="Порт-Аркадия",
        price="5 копеек",
        pages_count=4,
    )


def sample_project() -> Project:
    """Свёрстанный выпуск: главная статья, подвал из трёх материалов, врезки."""
    publication = sample_publication()
    issue = Issue(number="14", date="Среда, 12 июня", pages_count=4)
    project = new_project(issue, publication)

    lead = Article(
        rubric="ХРОНИКА ПРОИСШЕСТВИЙ",
        title="Ночной обвал в Нижнем доке: движение закрыто на трое суток",
        subtitle="Пострадавших нет. Смотритель складов отстранён до окончания дознания, "
        "грузы перенаправлены на Верхнюю пристань.",
        author="Записал М. Гроув",
        place_time="Нижний док, 11 июня, полночь",
        body=SAMPLE_BODY,
        image=ImageRef(
            caption="Третий пролёт утром 12 июня. Балку разбирали вручную, при фонарях.",
            height_px=96,
        ),
        continued_on=3,
    )
    footer = [
        Article(
            rubric="ГОРОДСКАЯ ЖИЗНЬ",
            title="Управа продлила комендантский час",
            body="До конца июня выход в портовую зону после одиннадцати — по пропускам. "
            "Пропуска выдают в конторе с девяти утра, по предъявлении рабочей книжки.",
            drop_cap=False,
        ),
        Article(
            rubric="ПОРТ И ТОРГ",
            title="«Ласточка» не вернулась к сроку",
            body="Катер вышел к Косе в понедельник и не дал вести. Поиски ведут две лодки; "
            "хозяин обещал награду тому, кто укажет верно.",
            drop_cap=False,
        ),
        Article(
            rubric="ПИСЬМА В РЕДАКЦИЮ",
            title="«Фонари на Косой не горят третью неделю»",
            body="Пишет лавочник П. Рогову: масло отпускают, а зажигать некому. "
            "Ответ конторы печатаем в следующем номере.",
            drop_cap=False,
        ),
    ]
    project.articles = [lead, *footer]

    front = project.pages[0]
    blocks = list(front.blocks())  # главная, боковая, три подвала
    project.assign(lead.id, blocks[0].id)
    for article, block in zip(footer, blocks[2:]):
        project.assign(article.id, block.id)

    sidebar = blocks[1]
    sidebar.kind = "module"
    sidebar.label = "Боковая колонка"
    weather = make_module("weather")
    weather.text = "Ветер с моря, к ночи туман. Днём +11°, ночью +6°. Барометр падает."
    rates = make_module("rates")
    rates.rows = [["Хлеб, фунт", "4 к."], ["Уголь, пуд", "21 к."], ["Наём лодки", "1 р. 10 к."]]
    quote = make_module("quote")
    quote.text = "«Кровлю держали на честном слове ещё с прошлой зимы»"
    quote.attribution = "ПОРТОВЫЙ МАСТЕР, ИМЯ НЕ НАЗВАНО"
    ad = make_module("ad")
    ad.text = (
        "Артель «Три якоря» берёт подряды на починку кровель и настилов. "
        "Спросить в лавке Рогова, Нижний док, 7."
    )
    obituary = make_module("obituary")
    obituary.text = "Тихо скончался смотритель маяка П. Зельке, 61 год. Прощание в пятницу."
    sidebar.modules = [weather, rates, quote, ad, obituary]
    return project
